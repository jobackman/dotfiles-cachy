-- Window rules wiki https://wiki.hypr.land/Configuring/Basics/Window-Rules/

-- Generic floating position
hl.window_rule({ match = { float = true }, center = true, persistent_size = true })

-- Picture-in-Picture
hl.window_rule({
    match             = { title = "^([Pp]icture[-\\s]?[Ii]n[-\\s]?[Pp]icture)(.*)$" },
    float             = true,
    keep_aspect_ratio = true,
    size              = { "max(monitor_w, monitor_h)*0.25", "min(monitor_w, monitor_h)*0.25" },
    pin               = true,
})

-- Gaming
local gamingApps = "^(steam_app.*|gamescope)$"
local gamingWorkspace = "name:gaming"

-- Launchers run through Proton, so their class looks like a game (steam_app_*).
-- Exclude them from the generic gaming rules by title; handled separately below.
local gameLaunchers   = "^(Battle\\.net|Ascension Launcher)$"
local notGameLauncher = "negative:^(Battle\\.net|Ascension Launcher)$"

hl.window_rule({ match = { content = "game", initial_title = notGameLauncher }, workspace = gamingWorkspace })
hl.window_rule({ match = { xdg_tag = "^(.*game.*)$" }, workspace = gamingWorkspace, fullscreen_state = 2, content = "game", sync_fullscreen = true })
hl.window_rule({ match = { class = gamingApps, initial_title = notGameLauncher }, workspace = gamingWorkspace })
hl.window_rule({ match = { class = "^(steam)$", title = "^(Friends List)$" }, float = true })
hl.window_rule({ match = { class = "^(steam)$", title = "^(Launching\\.{3})$" }, float = true, center = true, workspace = gamingWorkspace })
hl.window_rule({
    match = {
        class         = gamingApps,
        title         = "^(.+)$",
        initial_title = "negative:^(.*\\\\home\\\\.*)$",
    },
    content          = "game",
    decorate         = false,
    fullscreen_state = 2,
    size             = { "monitor_w", "monitor_h" },
    sync_fullscreen  = true,
})
hl.window_rule({
    match = {
        class         = "^(steam_app.*)$",
        initial_title = "^$",
    },
    center           = true,
    float            = true,
    fullscreen       = false,
    fullscreen_state = 0,
    workspace        = gamingWorkspace,
})

-- Launchers via Proton: excluded from gaming workspace above; open floating on current workspace.
-- initial_title variant applies at map time (title may still be empty when the window maps).
local launcherProps = {
    float            = true,
    fullscreen       = false,
    fullscreen_state = 0,
    sync_fullscreen  = false,
    size             = { "monitor_w*0.60", "monitor_h*0.60" },
    center           = true,
    persistent_size  = true,
}
local function ruleWith(match, name)
    local rule = { match = match, name = name }
    for k, v in pairs(launcherProps) do rule[k] = v end
    return rule
end
hl.window_rule(ruleWith({ initial_title = gameLaunchers }, "game-launcher-map"))
hl.window_rule(ruleWith({ title = gameLaunchers }, "game-launcher-runtime"))

